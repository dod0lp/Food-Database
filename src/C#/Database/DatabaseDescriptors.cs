        /// This constant holds the name of the table where food data is stored without prefix of database name.
        /// It can be used to construct SQL queries and access food data.
        /// </remarks>
        public const string Food = "Food";

        /// <summary>
        /// The name of the table in the database that stores food ingredients.
        /// </summary>
        /// <remarks>
        /// This constant holds the name of the table where ingredient data is stored without prefix of database name.
        /// It can be used to construct SQL queries and access ingredient data.
        /// </remarks>
        public const string FoodIngredients = "FoodIngredients";

        /// <summary>
        /// The name of the table in the database that stores user created food.
        /// </summary>
        /// <remarks>
        /// This constant holds the name of the table where user created food data is stored without prefix of database name.
        /// It can be used to construct SQL queries and access user created food data.
        /// </remarks>
        public const string UserCreatedFood = "UserCreatedFood";

        /// <summary>
        /// The name of the table in the database that stores user favorite foods.
        /// </summary>
        /// <remarks>
        /// This constant holds the name of the table where user favorite foods data is stored without prefix of database name.
        /// It can be used to construct SQL queries and access user favorite foods data.
        /// </remarks>
        public const string UserFoodFavorites = "UserFoodFavorites";

        /// <summary>
        /// The name of the table in the database that stores user food saved data like weight and price.
        /// </summary>
        /// <remarks>
        /// This constant holds the name of the table where food saved data data is stored without prefix of database name.
        /// It can be used to construct SQL queries and access food saved data data.
        /// </remarks>
