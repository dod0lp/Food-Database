        /// </remarks>
        public const string UserFoodRemarks = "UserFoodRemarks";

        /// <summary>
        /// The name of the table in the database that stores users.
        /// </summary>
        /// <remarks>
        /// This constant holds the name of the table where users data is stored without prefix of database name.
